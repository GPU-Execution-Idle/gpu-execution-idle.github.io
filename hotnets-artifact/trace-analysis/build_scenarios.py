"""Turn an agent trace + a scenario selection into web/shared/scenarios.generated.js.

    python3 build_scenarios.py --suggest            # list candidate tool calls with stats
    python3 build_scenarios.py                      # export the calls named in selection.json

Input trace CSV columns: session_id, agent, seq, kind (inference|tool), name, start_s, end_s
(see README.md for how to convert real traces into this shape).

Causality rule: a call's `history` holds durations of same-name tool calls whose
end_s <= this call's start_s, i.e. only what a controller could have observed when the
tool call began. The call's own duration (`actualToolS`) and the following inference
are "future" and are only revealed by the frontend after the visitor commits.
"""
import argparse
import csv
import json
from pathlib import Path

HERE = Path(__file__).parent
DEFAULT_TRACE = HERE / "fixtures" / "synthetic_trace.csv"
DEFAULT_SELECTION = HERE / "selection.json"
DEFAULT_OUT = HERE.parent / "web" / "shared" / "scenarios.generated.js"
HISTORY_WINDOW = 12  # most recent observations shown to the visitor / used by predictors


def load(path: Path):
    with path.open() as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["seq"] = int(r["seq"])
        r["start_s"], r["end_s"] = float(r["start_s"]), float(r["end_s"])
        r["dur"] = r["end_s"] - r["start_s"]
    return rows


def history_for(call, rows):
    past = sorted((r for r in rows if r["kind"] == "tool" and r["name"] == call["name"]
                   and r["end_s"] <= call["start_s"]), key=lambda r: r["end_s"])
    return [round(r["dur"], 3) for r in past[-HISTORY_WINDOW:]]


def next_inference(call, rows):
    nxt = [r for r in rows if r["session_id"] == call["session_id"] and r["seq"] == call["seq"] + 1]
    return round(nxt[0]["dur"], 3) if nxt and nxt[0]["kind"] == "inference" else 1.0


def percentile(xs, p):  # linear interpolation; must match web/shared/sim.js
    s = sorted(xs)
    k = (len(s) - 1) * p
    lo = int(k)
    hi = min(lo + 1, len(s) - 1)
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def suggest(rows):
    print(f"{'session':8}{'seq':>4}  {'tool':14}{'actual':>8}{'mean':>8}{'p20':>8}{'min':>8}{'n':>4}")
    for c in (r for r in rows if r["kind"] == "tool"):
        h = history_for(c, rows)
        if len(h) < 5:
            continue
        print(f"{c['session_id']:8}{c['seq']:>4}  {c['name']:14}{c['dur']:8.2f}"
              f"{sum(h)/len(h):8.2f}{percentile(h, .2):8.2f}{min(h):8.2f}{len(h):>4}")


def export(rows, selection, out: Path, trace_path: Path):
    by_key = {(r["session_id"], r["seq"]): r for r in rows}
    scenarios = {}
    for sel in selection["scenarios"]:
        call = by_key[(sel["session_id"], sel["seq"])]
        assert call["kind"] == "tool", sel
        hist = history_for(call, rows)
        assert len(hist) >= 3, f"{sel['id']}: too little history"
        scenarios[sel["id"]] = {
            "id": sel["id"],
            "title": sel["title"],
            "story": sel["story"],
            "agent": call["agent"],
            "tool": call["name"],
            "history": hist,
            "actualToolS": round(call["dur"], 3),
            "nextInferenceS": next_inference(call, rows),
            "source": f"{trace_path.name}:{call['session_id']}#{call['seq']}",
        }
    payload = {
        "version": selection["version"],
        "synthetic": selection["synthetic"],
        "trace": trace_path.name,
        "scenarios": scenarios,
    }
    out.write_text("// GENERATED by trace-analysis/build_scenarios.py. Do not edit by hand.\n"
                   f"export const SCENARIO_SET = {json.dumps(payload, indent=2)};\n")
    print(f"wrote {len(scenarios)} scenarios ({payload['version']}) -> {out}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trace", type=Path, default=DEFAULT_TRACE)
    ap.add_argument("--selection", type=Path, default=DEFAULT_SELECTION)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--suggest", action="store_true")
    a = ap.parse_args()
    rows = load(a.trace)
    if a.suggest:
        suggest(rows)
    else:
        export(rows, json.loads(a.selection.read_text()), a.out, a.trace)


if __name__ == "__main__":
    main()
