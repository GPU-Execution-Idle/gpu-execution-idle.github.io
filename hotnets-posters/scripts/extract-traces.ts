// Copy the SWE-bench agent traces used by the interactive demo into src/content/traces.ts,
// keeping only what the poster draws: task, total time, and each tool call's start and duration.
//
//   deno run -A scripts/extract-traces.ts
import { CONTROLLER_TRACES } from '../../hotnets-artifact/web/shared/controller-trace.generated.js';

type Idle = { startS: number; durS: number };
const traces = CONTROLLER_TRACES.map((t: { task: string; totalS: number; idle: Idle[] }) => ({
  task: t.task, totalS: t.totalS, calls: t.idle.map((p) => [p.startS, p.durS]),
}));
const out = new URL('../src/content/traces.ts', import.meta.url);
await Deno.writeTextFile(out, '// GENERATED by scripts/extract-traces.ts from the measured mini-SWE-agent traces (L40S)\n'
  + '// in hotnets-artifact/web/shared/controller-trace.generated.js. calls: [start s, duration s] per tool call.\n'
  + `export const AGENT_TRACES: { task: string; totalS: number; calls: [number, number][] }[] = ${JSON.stringify(traces)};\n`);
console.log('wrote src/content/traces.ts:', traces.map((t: { task: string; calls: unknown[] }) => `${t.task} (${t.calls.length} calls)`).join(', '));
